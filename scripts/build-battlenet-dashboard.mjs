import { readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(process.argv[2] ?? resolve(root, "../outputs"));
const shared = (await readFile(resolve(root, "supabase/functions/_shared/battlenet-oauth.ts"), "utf8"))
  .replace(/^export /gm, "");
const entry = (await readFile(resolve(root, "supabase/functions/battlenet-oauth/index.ts"), "utf8"))
  .replace(/^import .* from "\.\.\/_shared\/battlenet-oauth\.ts";\r?\n/m, "");
await mkdir(output, { recursive: true });
await writeFile(resolve(output, "battlenet-oauth-dashboard.ts"),
  "// Generated by scripts/build-battlenet-dashboard.mjs. No client secret belongs in this file.\n" + shared + "\n" + entry);
await writeFile(resolve(output, "20261012220000_battlenet_oauth.sql"),
  await readFile(resolve(root, "supabase/migrations/20261012220000_battlenet_oauth.sql"), "utf8"));
console.log(`Battle.net Dashboard code and SQL written to ${output}`);
